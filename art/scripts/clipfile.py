"""Writes the game's clip module, src/shared/Anim/Clips, as a folder: init.luau joins Part1.luau,
Part2.luau... (Roblox keeps a script's source under about 200 000 characters, so the clips are cut
into parts of at most CHUNK_CHARS). No Blender needed: export_anims.py hands it each clip's lines,
and rbxsim.py reads the parts back.

Run directly (with any Python) to cut an old single-file Clips.luau into the folder:
    python art/scripts/clipfile.py
"""

import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
ANIM = os.path.join(ROOT, "src", "shared", "Anim")
FOLDER = os.path.join(ANIM, "Clips")
LEGACY = os.path.join(ANIM, "Clips.luau")

CHUNK_CHARS = 150_000

HEADER = [
    "--!strict",
    "-- GENERATED by art/scripts/export_anims.py from art/blend/Animations.blend. Do not edit by hand:",
    "-- change the keys in art/scripts/anims.py (or the actions in Blender) and export again.",
]

FORMAT = [
    "--",
    "-- R6 joints: root, neck, rShoulder, lShoulder, rHip, lHip. Each clip: length (seconds), loop, and per joint the key times with quaternions",
    "-- (x, y, z, w) in the joint's parent frame, and p (x, y, z studs)",
    "-- where the part also slides in that frame; offset moves the whole body (studs).",
    "-- Movement clips also give their stride: studs covered per cycle by a leg `leg` long.",
]


def _write(path, lines):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return path


def _facts(lines):
    """(length, loop) from a clip's lines (its second and third lines, as clip_lua writes them)."""
    length, loop = 0.0, False
    for line in lines[1:4]:
        m = re.match(r"^\t\tlength = ([-\d.]+),$", line)
        if m:
            length = float(m.group(1))
        if line.strip() == "loop = true,":
            loop = True
    return length, loop


def write(clips):
    """clips: [(name, [lines])] in order, each clip's lines as export_anims.clip_lua makes them
    (starting "\\t<name> = {" and ending "\\t},"). Returns the files written."""
    parts, current, size = [], [], 0
    index = []  # (name, part, length, loop)
    for name, lines in clips:
        chars = sum(len(line) + 1 for line in lines)
        if current and size + chars > CHUNK_CHARS:
            parts.append(current)
            current, size = [], 0
        current.extend(lines)
        size += chars
        length, loop = _facts(lines)
        index.append((name, len(parts) + 1, length, loop))
    if current:
        parts.append(current)
    os.makedirs(FOLDER, exist_ok=True)
    for name in os.listdir(FOLDER):
        if re.fullmatch(r"Part\d+\.luau|Index\.luau", name):
            os.remove(os.path.join(FOLDER, name))
    written = []
    for i, lines in enumerate(parts, 1):
        head = HEADER + [f"-- Part {i} of {len(parts)} of the clips (Clips/init.luau joins them)."] + FORMAT
        written.append(_write(os.path.join(FOLDER, f"Part{i}.luau"), head + ["", "return {"] + lines + ["}"]))
    index_lines = HEADER + [
        "-- Every clip by id: the part that holds it, its length (seconds) and whether it loops. Small, so the server",
        "-- and the menus can know a clip without loading its keys.",
        "",
        "return {",
    ] + [f"\t{name} = {{ part = {part}, length = {length:g}, loop = {'true' if loop else 'false'} }},"
         for name, part, length, loop in index] + ["}"]
    written.append(_write(os.path.join(FOLDER, "Index.luau"), index_lines))
    refs = ", ".join(f"script.Part{i}" for i in range(1, len(parts) + 1))
    init = HEADER + [
        "-- Every clip by id. A part (each a table of clips, see Part1) loads the first time one of its clips is asked",
        "-- for, so a client only parses the keys it plays; Index knows every clip's part. To go through all of them,",
        "-- go through Index.",
        "",
        "local Index = require(script.Index) :: { [string]: { part: number, length: number, loop: boolean } }",
        f"local parts = {{ {refs} }}",
        "local loaded: { [number]: boolean } = {}",
        "local clips = {}",
        "",
        "local function load(n: number)",
        "\tif loaded[n] then",
        "\t\treturn",
        "\tend",
        "\tloaded[n] = true",
        "\tfor id, clip in pairs(require(parts[n]) :: any) do",
        "\t\trawset(clips, id, clip)",
        "\tend",
        "end",
        "",
        "setmetatable(clips, {",
        "\t__index = function(_, id)",
        "\t\tlocal entry = Index[id]",
        "\t\tif entry then",
        "\t\t\tload(entry.part)",
        "\t\t\treturn rawget(clips, id)",
        "\t\tend",
        "\t\treturn nil",
        "\tend,",
        "})",
        "return clips :: { [string]: any }",
    ]
    written.insert(0, _write(os.path.join(FOLDER, "init.luau"), init))
    if os.path.exists(LEGACY):
        os.remove(LEGACY)
    return written


def part_files():
    """The part files in order (Part1, Part2...), or the old single file if there is no folder."""
    if not os.path.isdir(FOLDER):
        return [LEGACY]
    names = [n for n in os.listdir(FOLDER) if re.fullmatch(r"Part\d+\.luau", n)]
    names.sort(key=lambda n: int(re.search(r"\d+", n).group(0)))
    return [os.path.join(FOLDER, n) for n in names]


def _split_legacy(path):
    """Cuts an old single-file Clips.luau into [(name, lines)]."""
    lines = open(path, encoding="utf-8").read().split("\n")
    start = lines.index("return {") + 1
    clips, current = [], None
    for line in lines[start:]:
        match = re.match(r"^\t(\w+) = \{$", line)
        if match:
            current = (match.group(1), [line])
            clips.append(current)
        elif current is not None:
            current[1].append(line)
            if line == "\t},":
                current = None
    return clips


if __name__ == "__main__":
    if not os.path.exists(LEGACY):
        raise SystemExit("No single-file Clips.luau to cut.")
    clips = _split_legacy(LEGACY)
    for f in write(clips):
        print(os.path.relpath(f, ROOT), os.path.getsize(f))
    print(len(clips), "clips")
